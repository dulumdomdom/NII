def lab3_numbers() -> dict:
    long_df = pd.read_csv(L3 / "metrics_vs_horizon.csv", encoding="utf-8-sig")
    summary = pd.read_csv(L3 / "models_summary.csv", index_col=0, encoding="utf-8-sig")
    fc = pd.read_csv(L3 / "final_forecast_2017.csv", encoding="utf-8-sig")
    cv = pd.read_csv(L3 / "cv_scores.csv", encoding="utf-8-sig")
    y, yh = fc["Real"].to_numpy(), fc["Prediction"].to_numpy()
    mse = float(np.mean((y - yh) ** 2))
    r2_piv = long_df.pivot(index="horizon_months", columns="model", values="R2")
    best = r2_piv.stack().idxmax()
    return {
        "long": long_df, "summary": summary, "cv": cv, "r2_piv": r2_piv,
        "best_model": summary.index[0], "best_mean_r2": summary.iloc[0]["mean_R2"],
        "best_h": best, "best_h_r2": float(r2_piv.stack().max()),
        "R2": 1 - np.sum((y - yh) ** 2) / np.sum((y - y.mean()) ** 2),
        "MSE": mse, "RMSE": mse ** 0.5, "MAE": float(np.mean(np.abs(y - yh))),
        "mean": float(y.mean()),
    }


