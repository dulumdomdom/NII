class Doc(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if isinstance(flowable, Paragraph):
            name = flowable.style.name
            text = flowable.getPlainText()
            if name in ("PART", "H1", "H2"):
                level = {"PART": 0, "H1": 1, "H2": 2}[name]
                if level == 2 or text == "Содержание":
                    return
                key_ = f"h{abs(hash(text))}"
                self.canv.bookmarkPage(key_)
                self.canv.addOutlineEntry(text, key_, level=level, closed=level > 0)
                self.notify("TOCEntry", (level, text, self.page, key_))


def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont("DejaVu", 7.5)
    canvas.setFillColor(colors.HexColor("#777777"))
    canvas.drawString(16 * mm, 9 * mm, "Конспект к защите ЛР №3 и ЛР №4 • " + AUTHOR)
    canvas.drawRightString(A4[0] - 16 * mm, 9 * mm, f"стр. {doc.page}")
    canvas.setStrokeColor(colors.HexColor("#c8d2dc"))
    canvas.line(16 * mm, 12 * mm, A4[0] - 16 * mm, 12 * mm)
    canvas.restoreState()


